package modules.explorer.domain;

import java.util.List;

import org.junit.jupiter.api.Test;

import testcase.AbstractTestCase;

import modules.explorer.domain.enums.TableIndexTypeEnum;
import modules.explorer.domain.entities.TableColumnEntity;
import modules.explorer.domain.entities.TableDefinitionEntity;
import modules.explorer.domain.entities.TableIndexEntity;
import modules.explorer.domain.services.TableCreateSqlBuilder;
import modules.explorer.domain.mothers.TableDefinitionMother;

/**
 * "Crear tabla" en cada motor: lo que cambia es el auto incremento, donde van los indices y los comentarios, y lo que
 * solo es de MySQL sale como error.
 */
final class TableCreateSqlBuilderTest extends AbstractTestCase {

    @Test
    void testPostgresqlUsesIdentityIndexesApartAndCommentOn() {
        List<String> statements = TableCreateSqlBuilder.getInstance("pgsql").getStatements("app", TableDefinitionMother.getOrders("int", "con IVA", "pedidos"));

        assertEquals(List.of(
            """
                CREATE TABLE "app"."orders" (
                    "id" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                    "customer_id" int NULL,
                    "total" decimal(10,2) NOT NULL DEFAULT 0,
                    PRIMARY KEY ("id"),
                    CONSTRAINT "uq_orders_total" UNIQUE ("total", "id"),
                    CONSTRAINT "fk_orders_customer" FOREIGN KEY ("customer_id") REFERENCES "app"."customers" ("id") ON DELETE CASCADE ON UPDATE RESTRICT
                )""",
            "CREATE INDEX \"ix_orders_customer\" ON \"app\".\"orders\" (\"customer_id\")",
            "COMMENT ON TABLE \"app\".\"orders\" IS 'pedidos'",
            "COMMENT ON COLUMN \"app\".\"orders\".\"total\" IS 'con IVA'"
        ), statements);
    }

    @Test
    void testSqliteAutoIncrementsTheIntegerRowIdKey() {
        List<String> statements = TableCreateSqlBuilder.getInstance("sqlite").getStatements("main", TableDefinitionMother.getOrders("INTEGER", "", ""));

        assertEquals(List.of(
            """
                CREATE TABLE "orders" (
                    "id" INTEGER PRIMARY KEY AUTOINCREMENT,
                    "customer_id" int NULL,
                    "total" decimal(10,2) NOT NULL DEFAULT 0,
                    CONSTRAINT "uq_orders_total" UNIQUE ("total", "id"),
                    CONSTRAINT "fk_orders_customer" FOREIGN KEY ("customer_id") REFERENCES "customers" ("id") ON DELETE CASCADE ON UPDATE RESTRICT
                )""",
            "CREATE INDEX \"ix_orders_customer\" ON \"orders\" (\"customer_id\")"
        ), statements);
    }

    @Test
    void testSqlServerRunsEachStatementInsideItsDatabase() {
        List<String> statements = TableCreateSqlBuilder.getInstance("mssql").getStatements("shop", TableDefinitionMother.getOrders("int", "", ""));

        assertEquals(2, statements.size());
        assertTrue(statements.getFirst().startsWith("EXEC [shop].sys.sp_executesql N'CREATE TABLE [dbo].[orders] (\n    [id] int IDENTITY(1,1) NOT NULL,"));
        assertTrue(statements.getFirst().contains("REFERENCES [dbo].[customers] ([id]) ON DELETE CASCADE ON UPDATE NO ACTION"));
        assertEquals("EXEC [shop].sys.sp_executesql N'CREATE INDEX [ix_orders_customer] ON [dbo].[orders] ([customer_id])'", statements.get(1));
    }

    @Test
    void testMysqlOnlyOptionsAreErrorsElsewhere() {
        TableDefinitionEntity orders = TableDefinitionMother.getOrders("varchar", "con IVA", "");
        TableColumnEntity unsignedColumn = new TableColumnEntity("", "qty", "int", "", true, true, false, false, "", "CURRENT_TIMESTAMP", "", "", "", false);
        TableDefinitionEntity withMysqlOptions = new TableDefinitionEntity(
            orders.tableName(), List.of(orders.columns().getFirst(), unsignedColumn), orders.primaryKeyColumns(),
            List.of(new TableIndexEntity("", "ft_qty", TableIndexTypeEnum.FULLTEXT, List.of("qty"))), List.of(),
            "InnoDB", "utf8mb4_bin", "", "10", "DYNAMIC"
        );

        List<String> pgsqlErrors = TableCreateSqlBuilder.getInstance("pgsql").getErrors(withMysqlOptions);
        List<String> sqliteErrors = TableCreateSqlBuilder.getInstance("sqlite").getErrors(orders);

        assertEquals(8, pgsqlErrors.size());
        assertEquals(2, sqliteErrors.size());
        assertEquals(List.of(), TableCreateSqlBuilder.getInstance("pgsql").getErrors(TableDefinitionMother.getOrders("int", "con IVA", "pedidos")));
        assertFalse(TableCreateSqlBuilder.getInstance("redis").isSupported());
        assertTrue(TableCreateSqlBuilder.getInstance("files").isSupported());
    }
}
