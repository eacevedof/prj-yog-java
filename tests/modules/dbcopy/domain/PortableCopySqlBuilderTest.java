package modules.dbcopy.domain;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

import org.junit.jupiter.api.Test;

import modules.shared.application.Primitives;

import testcase.AbstractTestCase;

import modules.dbcopy.domain.enums.DbCopyTypeFamilyEnum;
import modules.dbcopy.domain.entities.PortableColumnEntity;
import modules.dbcopy.domain.services.PortableColumnMapper;
import modules.dbcopy.domain.services.PortableCopySqlBuilder;
import modules.dbcopy.domain.exceptions.DbCopyException;

final class PortableCopySqlBuilderTest extends AbstractTestCase {

    private final PortableColumnMapper portableColumnMapper = PortableColumnMapper.getInstance();

    @Test
    void mysql_types_become_their_postgresql_sql_server_and_sqlite_equivalents() {
        assertTargetTypes("mysql", "int(10) unsigned", "int", "", "bigint", "bigint", "INTEGER", "int unsigned");
        assertTargetTypes("mysql", "bigint(20) unsigned", "bigint", "", "numeric(20,0)", "decimal(20,0)", "INTEGER", "bigint unsigned");
        assertTargetTypes("mysql", "tinyint(1)", "tinyint", "", "smallint", "smallint", "INTEGER", "tinyint");
        assertTargetTypes("mysql", "bit(1)", "bit", "", "boolean", "bit", "BOOLEAN", "tinyint(1)");
        assertTargetTypes("mysql", "varchar(100)", "varchar", "", "varchar(100)", "nvarchar(100)", "TEXT", "varchar(100)");
        assertTargetTypes("mysql", "longtext", "longtext", "", "text", "nvarchar(max)", "TEXT", "longtext");
        assertTargetTypes("mysql", "decimal(12,4)", "decimal", "", "numeric(12,4)", "decimal(12,4)", "NUMERIC", "decimal(12,4)");
        assertTargetTypes("mysql", "double", "double", "", "double precision", "float", "REAL", "double");
        assertTargetTypes("mysql", "datetime(3)", "datetime", "", "timestamp(3)", "datetime2(3)", "DATETIME", "datetime(3)");
        assertTargetTypes("mysql", "json", "json", "", "jsonb", "nvarchar(max)", "TEXT", "json");
        assertTargetTypes("mysql", "blob", "blob", "", "bytea", "varbinary(max)", "BLOB", "longblob");
        assertTargetTypes("mysql", "binary(4)", "binary", "", "bytea", "binary(4)", "BLOB", "binary(4)");
        assertTargetTypes("mysql", "enum('s','m','l')", "enum", "", "varchar(255)", "nvarchar(255)", "TEXT", "varchar(255)");
        assertTargetTypes("mysql", "year", "year", "", "smallint", "smallint", "INTEGER", "smallint");
    }

    @Test
    void postgresql_and_sql_server_types_come_back_to_mysql() {
        assertEquals("tinyint(1)", getTargetType("pgsql", "boolean", "bool", "mysql", false));
        assertEquals("char(36)", getTargetType("pgsql", "uuid", "uuid", "mysql", false));
        assertEquals("datetime(6)", getTargetType("pgsql", "timestamp without time zone", "timestamp", "mysql", false));
        assertEquals("datetime(6)", getTargetType("pgsql", "timestamp with time zone", "timestamptz", "mysql", false));
        assertEquals("longtext", getTargetType("pgsql", "text", "text", "mysql", false));
        assertEquals("varchar(255)", getTargetType("pgsql", "text", "text", "mysql", true));
        assertEquals("decimal(65,30)", getTargetType("pgsql", "numeric", "numeric", "mysql", false));
        assertEquals("tinyint unsigned", getTargetType("mssql", "tinyint", "tinyint", "mysql", false));
        assertEquals("tinyint", getTargetType("mssql", "tinyint", "tinyint", "mssql", false));
        assertEquals("datetime(3)", getTargetType("mssql", "datetime", "datetime", "mysql", false));
        assertEquals("float", getTargetType("mssql", "real", "real", "mysql", false));
        assertEquals("double", getTargetType("mssql", "float", "float", "mysql", false));
        assertEquals("bigint", getTargetType("sqlite", "integer", "integer", "pgsql", false));
        assertEquals("text", getTargetType("sqlite", "(sin tipo)", "", "pgsql", false));
    }

    @Test
    void the_identity_key_gets_the_autoincrement_of_each_engine() {
        List<PortableColumnEntity> columns = List.of(
            portableColumnMapper.getPortableColumn("mysql", "id", "int(10) unsigned", "int", false, "auto_increment"),
            portableColumnMapper.getPortableColumn("mysql", "name", "varchar(20)", "varchar", true, "")
        );
        assertEquals(
            "CREATE TABLE \"s\".\"t\" (\n    \"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n    \"name\" varchar(20),\n    PRIMARY KEY (\"id\")\n)",
            getCreateTable("pgsql", columns)
        );
        assertEquals(
            "CREATE TABLE [s].[dbo].[t] (\n    [id] bigint IDENTITY(1,1) NOT NULL,\n    [name] nvarchar(20),\n    PRIMARY KEY ([id])\n)",
            getCreateTable("mssql", columns)
        );
        assertEquals("CREATE TABLE \"t\" (\n    \"id\" INTEGER PRIMARY KEY,\n    \"name\" TEXT\n)", getCreateTable("sqlite", columns));
        assertEquals(
            "CREATE TABLE `s`.`t` (\n    `id` int NOT NULL AUTO_INCREMENT,\n    `name` varchar(20),\n    PRIMARY KEY (`id`)\n)",
            PortableCopySqlBuilder.getInstance("pgsql", "mysql", false).getCreateTableSql(
                "s", "t",
                List.of(
                    portableColumnMapper.getPortableColumn("pgsql", "id", "integer", "int4", false, "auto_increment"),
                    portableColumnMapper.getPortableColumn("pgsql", "name", "character varying(20)", "varchar", true, "")
                ),
                List.of("int", "varchar(20)"), List.of("id")
            )
        );
    }

    @Test
    void values_are_written_as_literals_of_the_target() {
        PortableCopySqlBuilder toPgsql = PortableCopySqlBuilder.getInstance("mysql", "pgsql", false);
        PortableCopySqlBuilder toMssql = PortableCopySqlBuilder.getInstance("mysql", "mssql", false);
        PortableCopySqlBuilder toSqlite = PortableCopySqlBuilder.getInstance("mysql", "sqlite", false);
        PortableCopySqlBuilder toMysql = PortableCopySqlBuilder.getInstance("pgsql", "mysql", false);

        assertEquals("TRUE", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.BOOLEAN), "1"));
        assertEquals("1", toMysql.getLiteral(getColumn(DbCopyTypeFamilyEnum.BOOLEAN), "t"));
        assertEquals("0", toMssql.getLiteral(getColumn(DbCopyTypeFamilyEnum.BOOLEAN), "false"));
        assertEquals("'\\xcafe'", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.BINARY), new byte[] {(byte) 0xca, (byte) 0xfe}));
        assertEquals("0xcafe", toMssql.getLiteral(getColumn(DbCopyTypeFamilyEnum.BINARY), new byte[] {(byte) 0xca, (byte) 0xfe}));
        assertEquals("X'cafe'", toSqlite.getLiteral(getColumn(DbCopyTypeFamilyEnum.BINARY), new byte[] {(byte) 0xca, (byte) 0xfe}));
        assertEquals("'O''Brien \\ x'", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.TEXT), "O'Brien \\ x"));
        assertEquals("'O''Brien \\ x'", toSqlite.getLiteral(getColumn(DbCopyTypeFamilyEnum.TEXT), "O'Brien \\ x"));
        assertEquals("N'O''Brien'", toMssql.getLiteral(getColumn(DbCopyTypeFamilyEnum.TEXT), "O'Brien"));
        assertEquals("'O\\'Brien \\\\ x'", toMysql.getLiteral(getColumn(DbCopyTypeFamilyEnum.TEXT), "O'Brien \\ x"));
        assertEquals("'2024-02-29 23:59:59.123'", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DATETIME), "2024-02-29 23:59:59.123000"));
        assertEquals("'2024-02-29T23:59:59'", toMssql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DATETIME), "2024-02-29 23:59:59"));
        assertEquals("'2024-06-01 10:00:00'", toMysql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DATETIME), "2024-06-01 10:00:00+02"));
        assertEquals("NULL", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DATETIME), "0000-00-00 00:00:00"));
        assertEquals("NULL", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DATE), "0000-00-00"));
        assertEquals("'1999-12-31'", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DATE), "1999-12-31"));
        assertEquals("'08:30:00.5'", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.TIME), "08:30:00.500"));
        assertEquals("'-12:30:00'", PortableCopySqlBuilder.getInstance("mysql", "mysql", false).getLiteral(getColumn(DbCopyTypeFamilyEnum.TIME), "-12:30:00"));
        assertEquals("1234", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.INTEGER), "1234"));
        assertEquals("3", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.INTEGER), "3.0"));
        assertEquals("12345678.1234", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.DECIMAL), "12345678.1234"));
        assertEquals("'NaN'", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.FLOAT), "NaN"));
        assertEquals("NULL", toMysql.getLiteral(getColumn(DbCopyTypeFamilyEnum.FLOAT), "NaN"));
        assertEquals("NULL", toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.TEXT), null));
        assertEquals("(1, NULL, 'a')", toPgsql.getRowTuple(
            List.of(getColumn(DbCopyTypeFamilyEnum.INTEGER), getColumn(DbCopyTypeFamilyEnum.TEXT), getColumn(DbCopyTypeFamilyEnum.TEXT)),
            new ArrayList<>(Arrays.asList("1", null, "a"))
        ));
    }

    @Test
    void a_value_that_does_not_fit_its_type_fails_with_the_column() {
        PortableCopySqlBuilder toPgsql = PortableCopySqlBuilder.getInstance("sqlite", "pgsql", false);
        DbCopyException exception = assertThrows(DbCopyException.class, () -> toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.INTEGER), "abc"));
        assertTrue(exception.getMessage().contains("abc"));
        assertThrows(DbCopyException.class, () -> toPgsql.getLiteral(getColumn(DbCopyTypeFamilyEnum.TIME), "-12:30:00"));
        assertThrows(DbCopyException.class, () -> PortableCopySqlBuilder.getInstance("mysql", "sqlite", false).getCreateDatabaseSql("otra"));
    }

    @Test
    void pages_and_indexes_follow_each_dialect() {
        List<PortableColumnEntity> columns = List.of(
            portableColumnMapper.getPortableColumn("mysql", "id", "int", "int", false, ""),
            portableColumnMapper.getPortableColumn("mysql", "flag", "bit(1)", "bit", true, "")
        );
        assertEquals(
            "SELECT `id`, CAST(`flag` AS UNSIGNED) AS `flag` FROM `db`.`t` WHERE `id` > 1000 ORDER BY `id` LIMIT 1000",
            PortableCopySqlBuilder.getInstance("mysql", "pgsql", false).getSelectPageSql("db", "t", columns, List.of("id"), "id", "1000", 1000, 1000)
        );
        assertEquals(
            "SELECT TOP 1000 [id], [flag] FROM [db].[dbo].[t] ORDER BY [id]",
            PortableCopySqlBuilder.getInstance("mssql", "pgsql", false).getSelectPageSql("db", "t", columns, List.of("id"), "id", "", 1000, 0)
        );
        assertEquals(
            "SELECT [id], [flag] FROM [db].[dbo].[t] ORDER BY (SELECT NULL) OFFSET 2000 ROWS FETCH NEXT 1000 ROWS ONLY",
            PortableCopySqlBuilder.getInstance("mssql", "pgsql", false).getSelectPageSql("db", "t", columns, List.of(), "", "", 1000, 2000)
        );
        assertEquals(
            "CREATE UNIQUE INDEX \"customers_email\" ON \"s\".\"customers\" (\"email\")",
            PortableCopySqlBuilder.getInstance("mysql", "pgsql", false).getCreateIndexSql("s", "customers", "email", true, List.of("email"))
        );
        assertEquals(
            "CREATE INDEX `ix_name` ON `s`.`customers` (`name`, `id`)",
            PortableCopySqlBuilder.getInstance("pgsql", "mysql", false).getCreateIndexSql("s", "customers", "ix_name", false, List.of("name", "id"))
        );
        assertEquals("CREATE SCHEMA IF NOT EXISTS \"x\"", PortableCopySqlBuilder.getInstance("mysql", "pgsql", false).getCreateDatabaseSql("x"));
    }

    private void assertTargetTypes(
        String sourceEngine, String columnType, String dataType, String extra, String pgsql, String mssql, String sqlite, String mysql
    ) {
        PortableColumnEntity column = portableColumnMapper.getPortableColumn(sourceEngine, "c", columnType, dataType, true, extra);
        assertEquals(columnType + " -> " + pgsql, columnType + " -> " + portableColumnMapper.getTargetType("pgsql", column, false, false));
        assertEquals(columnType + " -> " + mssql, columnType + " -> " + portableColumnMapper.getTargetType("mssql", column, false, false));
        assertEquals(columnType + " -> " + sqlite, columnType + " -> " + portableColumnMapper.getTargetType("sqlite", column, false, false));
        assertEquals(columnType + " -> " + mysql, columnType + " -> " + portableColumnMapper.getTargetType("mysql", column, false, false));
    }

    private String getTargetType(String sourceEngine, String columnType, String dataType, String targetEngine, boolean isIndexed) {
        PortableColumnEntity column = portableColumnMapper.getPortableColumn(sourceEngine, "c", columnType, dataType, true, "");
        return portableColumnMapper.getTargetType(targetEngine, column, isIndexed, false);
    }

    private String getCreateTable(String targetEngine, List<PortableColumnEntity> columns) {
        List<String> targetTypes = List.of(
            portableColumnMapper.getTargetType(targetEngine, columns.get(0), true, true),
            portableColumnMapper.getTargetType(targetEngine, columns.get(1), false, false)
        );
        String databaseName = "sqlite".equals(targetEngine) ? "main" : "s";
        return PortableCopySqlBuilder.getInstance("mysql", targetEngine, false).getCreateTableSql(databaseName, "t", columns, targetTypes, List.of("id"));
    }

    private PortableColumnEntity getColumn(String family) {
        return PortableColumnEntity.fromPrimitives(Primitives.of("name", "c", "family", family, "isNullable", true));
    }
}
