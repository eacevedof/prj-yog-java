package modules.dbcopy.domain.services;

import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import modules.shared.domain.services.SqlDialect;
import modules.shared.domain.services.SqlIdentifierQuoter;
import modules.shared.domain.services.SqlLiteralQuoter;

import static core.config.Global.__;

import modules.dbcopy.domain.enums.DbCopyMessageEnum;
import modules.dbcopy.domain.enums.DbCopyTypeFamilyEnum;
import modules.dbcopy.domain.entities.PortableColumnEntity;
import modules.dbcopy.domain.exceptions.DbCopyException;

/**
 * Copia entre motores: el SQL del origen (SELECT por paginas) y del destino (BD, tabla, indices e INSERT con literales)
 * para MySQL/MariaDB, PostgreSQL, SQL Server y SQLite. Todo va cualificado (`bd`.`t`, "esquema"."t", [bd].[dbo].[t]),
 * asi no depende de la BD activa de la sesion. Los valores llegan como texto (o bytes, los binarios) y se escriben
 * como literal del destino segun su tipo comun: el motor los convierte al tipo de la columna sin depender del driver.
 */
public final class PortableCopySqlBuilder {

    private static final Pattern DATETIME_PATTERN = Pattern.compile(
        "^(\\d{4})-(\\d{2})-(\\d{2})(?:[ T](\\d{1,2}):(\\d{2})(?::(\\d{2}))?(?:\\.(\\d+))?)?.*$"
    );
    private static final Pattern TIME_PATTERN = Pattern.compile("^(-?)(\\d{1,3}):(\\d{2})(?::(\\d{2}))?(?:\\.(\\d+))?$");
    private static final Pattern NUMBER_PATTERN = Pattern.compile("^[+-]?(?:\\d+\\.?\\d*|\\.\\d+)(?:[eE][+-]?\\d+)?$");
    private static final Set<String> TRUE_WORDS = Set.of("1", "t", "true", "y", "yes", "on");
    private static final Set<String> FALSE_WORDS = Set.of("0", "f", "false", "n", "no", "off");
    private static final int MAX_FRACTION_DIGITS = 6;
    private static final int MAX_IDENTIFIER_CHARS = 63;

    private final SqlDialect sourceDialect;
    private final SqlDialect targetDialect;
    private final SqlIdentifierQuoter sourceQuoter;
    private final SqlIdentifierQuoter targetQuoter;
    private final SqlLiteralQuoter targetLiteralQuoter;

    /**
     * isTargetTunnel: por el tunel PHP, el SQL de SQLite va con literales de estilo MySQL (el PHP los reescribe); por
     * JDBC, con los estandar ('it''s').
     */
    private PortableCopySqlBuilder(String sourceEngine, String targetEngine, boolean isTargetTunnel) {
        this.sourceDialect = SqlDialect.getInstance(sourceEngine);
        this.targetDialect = SqlDialect.getInstance(targetEngine);
        this.sourceQuoter = SqlIdentifierQuoter.getInstance(sourceDialect.getDbEngine());
        this.targetQuoter = SqlIdentifierQuoter.getInstance(targetDialect.getDbEngine());
        boolean isStandardStrings = targetDialect.isSqlite() && !isTargetTunnel;
        this.targetLiteralQuoter = SqlLiteralQuoter.getInstance(isStandardStrings ? SqlDialect.PGSQL : targetDialect.getDbEngine());
    }

    public static PortableCopySqlBuilder getInstance(String sourceEngine, String targetEngine, boolean isTargetTunnel) {
        return new PortableCopySqlBuilder(sourceEngine, targetEngine, isTargetTunnel);
    }

    /**
     * La BD destino que no existe: una BD en MySQL y SQL Server, un esquema en PostgreSQL. SQLite solo tiene main.
     * @throws DbCopyException si el destino es SQLite
     */
    public String getCreateDatabaseSql(String databaseName) {
        if (targetDialect.isSqlite()) throw DbCopyException.badRequestCustom(__(DbCopyMessageEnum.SQLITE_ONLY_MAIN_X, databaseName));
        if (targetDialect.isPgsql()) return "CREATE SCHEMA IF NOT EXISTS " + targetQuoter.getQuoted(databaseName);
        if (targetDialect.isMssql()) return "CREATE DATABASE " + targetQuoter.getQuoted(databaseName);
        return "CREATE DATABASE IF NOT EXISTS " + targetQuoter.getQuoted(databaseName) + " DEFAULT CHARACTER SET utf8mb4";
    }

    public String getDropTableSql(String databaseName, String tableName) {
        return "DROP TABLE IF EXISTS " + getTargetTable(databaseName, tableName);
    }

    /**
     * CREATE TABLE con columnas, NOT NULL, clave primaria y el autoincremento de la clave de una sola columna entera
     * (AUTO_INCREMENT, GENERATED BY DEFAULT AS IDENTITY, IDENTITY(1,1) o INTEGER PRIMARY KEY). targetTypes: el tipo de
     * cada columna en el destino (PortableColumnMapper), en el mismo orden.
     */
    public String getCreateTableSql(
        String databaseName, String tableName, List<PortableColumnEntity> columns, List<String> targetTypes, List<String> primaryKeyColumns
    ) {
        String identityColumn = getIdentityColumn(columns, primaryKeyColumns);
        List<String> definitions = new ArrayList<>();
        for (int i = 0; i < columns.size(); i++) {
            PortableColumnEntity column = columns.get(i);
            boolean isIdentity = column.name().equals(identityColumn);
            definitions.add(getColumnDefinition(column, targetTypes.get(i), isIdentity));
        }
        boolean isPrimaryKeyInline = targetDialect.isSqlite() && !identityColumn.isEmpty();
        if (!primaryKeyColumns.isEmpty() && !isPrimaryKeyInline) {
            definitions.add("PRIMARY KEY (" + getQuotedTargetList(primaryKeyColumns) + ")");
        }
        return "CREATE TABLE " + getTargetTable(databaseName, tableName) + " (\n    " + String.join(",\n    ", definitions) + "\n)";
    }

    /**
     * La columna que lleva el autoincremento en el destino: la de una clave primaria de una sola columna entera que lo
     * tenia en el origen; "" si ninguna.
     */
    public String getIdentityColumn(List<PortableColumnEntity> columns, List<String> primaryKeyColumns) {
        if (primaryKeyColumns.size() != 1) return "";
        for (PortableColumnEntity column : columns) {
            if (column.name().equals(primaryKeyColumns.getFirst()) && column.isAutoIncrement() && DbCopyTypeFamilyEnum.INTEGER.equals(column.family())) {
                return column.name();
            }
        }
        return "";
    }

    /**
     * CREATE [UNIQUE] INDEX. En PostgreSQL y SQLite el nombre es unico en todo el esquema: se le antepone la tabla si
     * no la lleva (dos tablas con un "ix_name" chocarian). Los automaticos de SQLite (sqlite_autoindex_...) no se
     * pueden crear con ese nombre.
     */
    public String getCreateIndexSql(String databaseName, String tableName, String indexName, boolean isUnique, List<String> columnNames) {
        String targetIndexName = getTargetIndexName(tableName, indexName);
        return "CREATE " + (isUnique ? "UNIQUE " : "") + "INDEX " + targetQuoter.getQuoted(targetIndexName) + " ON " + getTargetTable(databaseName, tableName)
            + " (" + getQuotedTargetList(columnNames) + ")";
    }

    /**
     * SQL Server: los INSERT con valor en la columna IDENTITY necesitan SET IDENTITY_INSERT ON en la sesion.
     */
    public String getIdentityInsertSql(String databaseName, String tableName, boolean isOn) {
        return "SET IDENTITY_INSERT " + getTargetTable(databaseName, tableName) + (isOn ? " ON" : " OFF");
    }

    /**
     * PostgreSQL: un IDENTITY no avanza con los INSERT que llevan el valor: se pone al maximo copiado para que el
     * siguiente INSERT sin id no choque.
     */
    public String getIdentityRestartSql(String databaseName, String tableName, String columnName) {
        String qualifiedTable = getTargetTable(databaseName, tableName);
        String quotedColumn = targetQuoter.getQuoted(columnName);
        return "SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence(" + targetLiteralQuoter.getLiteral(qualifiedTable) + ", "
            + targetLiteralQuoter.getLiteral(columnName) + "), m) FROM (SELECT MAX(" + quotedColumn + ") AS m FROM " + qualifiedTable
            + ") x WHERE m IS NOT NULL";
    }

    /**
     * Una pagina del origen. keysetColumn (clave primaria de una sola columna entera): las filas tras lastKeyValue, en
     * orden; si no, por desplazamiento (ordenado por la clave si la hay). SQL Server: TOP y OFFSET ... FETCH.
     */
    public String getSelectPageSql(
        String databaseName, String tableName, List<PortableColumnEntity> columns, List<String> primaryKeyColumns,
        String keysetColumn, String lastKeyValue, int limit, long offset
    ) {
        String selectList = getSelectList(columns);
        String sourceTable = sourceQuoter.getQuoted(databaseName, tableName);
        if (!keysetColumn.isEmpty()) {
            String quotedKey = sourceQuoter.getQuoted(keysetColumn);
            String where = lastKeyValue.isEmpty() ? "" : " WHERE " + quotedKey + " > " + lastKeyValue;
            if (sourceDialect.isMssql()) return "SELECT TOP " + limit + " " + selectList + " FROM " + sourceTable + where + " ORDER BY " + quotedKey;
            return "SELECT " + selectList + " FROM " + sourceTable + where + " ORDER BY " + quotedKey + " LIMIT " + limit;
        }
        String orderBy = primaryKeyColumns.isEmpty() ? "" : " ORDER BY " + getQuotedSourceList(primaryKeyColumns);
        if (sourceDialect.isMssql()) {
            if (orderBy.isEmpty()) orderBy = " ORDER BY (SELECT NULL)";
            return "SELECT " + selectList + " FROM " + sourceTable + orderBy + " OFFSET " + offset + " ROWS FETCH NEXT " + limit + " ROWS ONLY";
        }
        return "SELECT " + selectList + " FROM " + sourceTable + orderBy + " LIMIT " + limit + " OFFSET " + offset;
    }

    /**
     * "INSERT INTO <tabla cualificada> (cols) VALUES ".
     */
    public String getInsertPrefix(String databaseName, String tableName, List<PortableColumnEntity> columns) {
        List<String> columnNames = columns.stream().map(PortableColumnEntity::name).toList();
        return "INSERT INTO " + getTargetTable(databaseName, tableName) + " (" + getQuotedTargetList(columnNames) + ") VALUES ";
    }

    /**
     * "(1, 'Ana', NULL, ...)" con cada celda como literal del destino segun el tipo comun de su columna.
     * @throws DbCopyException si un valor no vale para su tipo (texto en una columna entera de SQLite...)
     */
    public String getRowTuple(List<PortableColumnEntity> columns, List<Object> cells) {
        StringBuilder rowTuple = new StringBuilder("(");
        for (int i = 0; i < columns.size(); i++) {
            if (i > 0) rowTuple.append(", ");
            rowTuple.append(getLiteral(columns.get(i), cells.get(i)));
        }
        return rowTuple.append(")").toString();
    }

    /**
     * El valor de la clave de keyset como literal numerico (vacio si no es un entero: no se usa para paginar).
     */
    public String getKeysetLiteral(Object cell) {
        if (cell == null) return "";
        String text = getText(cell).trim();
        return text.matches("-?\\d{1,19}") ? text : "";
    }

    /**
     * El literal del destino para una celda (texto del origen, bytes de un binario o null).
     * @throws DbCopyException
     */
    public String getLiteral(PortableColumnEntity column, Object cell) {
        if (cell == null) return "NULL";
        if (DbCopyTypeFamilyEnum.BINARY.equals(column.family())) return getBinaryLiteral(cell instanceof byte[] bytes ? bytes : getText(cell).getBytes(StandardCharsets.UTF_8));
        String text = getText(cell);
        return switch (column.family()) {
            case DbCopyTypeFamilyEnum.INTEGER -> getIntegerLiteral(column, text);
            case DbCopyTypeFamilyEnum.DECIMAL -> getDecimalLiteral(column, text);
            case DbCopyTypeFamilyEnum.FLOAT -> getFloatLiteral(column, text);
            case DbCopyTypeFamilyEnum.BOOLEAN -> getBooleanLiteral(column, text);
            case DbCopyTypeFamilyEnum.DATE -> getDateTimeLiteral(column, text, false);
            case DbCopyTypeFamilyEnum.DATETIME -> getDateTimeLiteral(column, text, true);
            case DbCopyTypeFamilyEnum.TIME -> getTimeLiteral(column, text);
            default -> targetLiteralQuoter.getLiteral(text);
        };
    }

    private String getColumnDefinition(PortableColumnEntity column, String targetType, boolean isIdentity) {
        StringBuilder definition = new StringBuilder(targetQuoter.getQuoted(column.name())).append(' ').append(targetType);
        if (isIdentity) {
            if (targetDialect.isSqlite()) return definition.append(" PRIMARY KEY").toString();
            if (targetDialect.isPgsql()) definition.append(" GENERATED BY DEFAULT AS IDENTITY");
            if (targetDialect.isMssql()) definition.append(" IDENTITY(1,1)");
        }
        if (!column.isNullable() || isIdentity) definition.append(" NOT NULL");
        if (isIdentity && targetDialect.isMysql()) definition.append(" AUTO_INCREMENT");
        return definition.toString();
    }

    private String getSelectList(List<PortableColumnEntity> columns) {
        StringBuilder selectList = new StringBuilder();
        for (PortableColumnEntity column : columns) {
            if (!selectList.isEmpty()) selectList.append(", ");
            String quotedName = sourceQuoter.getQuoted(column.name());
            if (column.isCastToNumber() && sourceDialect.isMysql()) {
                selectList.append("CAST(").append(quotedName).append(" AS UNSIGNED) AS ").append(quotedName);
                continue;
            }
            selectList.append(quotedName);
        }
        return selectList.toString();
    }

    private String getTargetTable(String databaseName, String tableName) {
        return targetQuoter.getQuoted(databaseName, tableName);
    }

    private String getTargetIndexName(String tableName, String indexName) {
        String plainTable = tableName.contains(".") ? tableName.substring(tableName.lastIndexOf('.') + 1) : tableName;
        String targetIndexName = indexName;
        if (indexName.toLowerCase(Locale.ROOT).startsWith("sqlite_")) targetIndexName = "ux_" + plainTable + "_" + indexName.replaceAll("\\D", "");
        else if ((targetDialect.isPgsql() || targetDialect.isSqlite()) && !indexName.toLowerCase(Locale.ROOT).startsWith(plainTable.toLowerCase(Locale.ROOT))) {
            targetIndexName = plainTable + "_" + indexName;
        }
        return targetIndexName.length() > MAX_IDENTIFIER_CHARS ? targetIndexName.substring(0, MAX_IDENTIFIER_CHARS) : targetIndexName;
    }

    private String getQuotedTargetList(List<String> identifiers) {
        return String.join(", ", identifiers.stream().map(targetQuoter::getQuoted).toList());
    }

    private String getQuotedSourceList(List<String> identifiers) {
        return String.join(", ", identifiers.stream().map(sourceQuoter::getQuoted).toList());
    }

    private String getIntegerLiteral(PortableColumnEntity column, String text) {
        String trimmed = text.trim();
        String lower = trimmed.toLowerCase(Locale.ROOT);
        if (TRUE_WORDS.contains(lower) && !lower.matches("\\d")) return "1";
        if (FALSE_WORDS.contains(lower) && !lower.matches("\\d")) return "0";
        BigDecimal number = getNumberOrFail(column, trimmed);
        BigDecimal integral = number.stripTrailingZeros();
        if (integral.scale() > 0) throw getWrongValueException(column, text);
        return integral.toBigInteger().toString();
    }

    private String getDecimalLiteral(PortableColumnEntity column, String text) {
        return getNumberOrFail(column, text.trim()).toPlainString();
    }

    /**
     * NaN e infinitos solo existen en PostgreSQL ('NaN'); en el resto quedan NULL.
     */
    private String getFloatLiteral(PortableColumnEntity column, String text) {
        String trimmed = text.trim();
        String lower = trimmed.toLowerCase(Locale.ROOT);
        if (lower.equals("nan") || lower.contains("inf")) {
            if (!targetDialect.isPgsql()) return "NULL";
            if (lower.equals("nan")) return "'NaN'";
            return lower.startsWith("-") ? "'-Infinity'" : "'Infinity'";
        }
        return getNumberOrFail(column, trimmed).toString();
    }

    private String getBooleanLiteral(PortableColumnEntity column, String text) {
        String lower = text.trim().toLowerCase(Locale.ROOT);
        boolean isTrue;
        if (TRUE_WORDS.contains(lower)) isTrue = true;
        else if (FALSE_WORDS.contains(lower)) isTrue = false;
        else isTrue = getNumberOrFail(column, lower).signum() != 0;
        if (targetDialect.isPgsql()) return isTrue ? "TRUE" : "FALSE";
        return isTrue ? "1" : "0";
    }

    /**
     * Fecha o fecha-hora en ISO ('2024-02-29 23:59:59.123'): la fecha cero de MySQL ('0000-00-00') y los infinitos de
     * PostgreSQL quedan NULL; la zona horaria se descarta; mas de 6 decimales de segundo se recortan. SQL Server: con T
     * (unica forma que no depende del idioma de la sesion).
     */
    private String getDateTimeLiteral(PortableColumnEntity column, String text, boolean isDateTime) {
        String trimmed = text.trim();
        if (trimmed.toLowerCase(Locale.ROOT).contains("infinity")) return "NULL";
        Matcher matcher = DATETIME_PATTERN.matcher(trimmed);
        if (!matcher.matches()) throw getWrongValueException(column, text);
        String date = matcher.group(1) + "-" + matcher.group(2) + "-" + matcher.group(3);
        if (matcher.group(1).equals("0000") || matcher.group(2).equals("00") || matcher.group(3).equals("00")) return "NULL";
        if (!isDateTime) return "'" + date + "'";
        String hours = matcher.group(4) == null ? "00" : String.format(Locale.ROOT, "%02d", Integer.parseInt(matcher.group(4)));
        String minutes = matcher.group(5) == null ? "00" : matcher.group(5);
        String seconds = matcher.group(6) == null ? "00" : matcher.group(6);
        String fraction = getFraction(matcher.group(7));
        return "'" + date + (targetDialect.isMssql() ? "T" : " ") + hours + ":" + minutes + ":" + seconds + fraction + "'";
    }

    /**
     * Hora 'HH:MM:SS[.ffffff]'. MySQL admite horas negativas o de mas de 24 (un TIME es una duracion); el resto no.
     */
    private String getTimeLiteral(PortableColumnEntity column, String text) {
        String trimmed = text.trim();
        Matcher matcher = TIME_PATTERN.matcher(trimmed);
        if (!matcher.matches()) {
            Matcher dateTimeMatcher = DATETIME_PATTERN.matcher(trimmed);
            if (dateTimeMatcher.matches() && dateTimeMatcher.group(4) != null) {
                return getTimeLiteral(column, trimmed.substring(11));
            }
            throw getWrongValueException(column, text);
        }
        int hours = Integer.parseInt(matcher.group(2));
        boolean isNegative = !matcher.group(1).isEmpty();
        if (!targetDialect.isMysql() && (isNegative || hours > 23)) throw getWrongValueException(column, text);
        String seconds = matcher.group(4) == null ? "00" : matcher.group(4);
        return "'" + matcher.group(1) + String.format(Locale.ROOT, "%02d", hours) + ":" + matcher.group(3) + ":" + seconds + getFraction(matcher.group(5)) + "'";
    }

    private String getFraction(String digits) {
        if (digits == null || digits.isEmpty()) return "";
        String trimmedDigits = digits.length() > MAX_FRACTION_DIGITS ? digits.substring(0, MAX_FRACTION_DIGITS) : digits;
        trimmedDigits = trimmedDigits.replaceAll("0+$", "");
        return trimmedDigits.isEmpty() ? "" : "." + trimmedDigits;
    }

    /**
     * X'cafe' en MySQL y SQLite, '\xcafe' en PostgreSQL (bytea con standard_conforming_strings) y 0xcafe en SQL Server.
     */
    private String getBinaryLiteral(byte[] bytes) {
        String hex = HexFormat.of().formatHex(bytes);
        if (targetDialect.isPgsql()) return "'\\x" + hex + "'";
        if (targetDialect.isMssql()) return "0x" + hex;
        return "X'" + hex + "'";
    }

    private BigDecimal getNumberOrFail(PortableColumnEntity column, String text) {
        if (!NUMBER_PATTERN.matcher(text).matches()) throw getWrongValueException(column, text);
        return new BigDecimal(text);
    }

    private DbCopyException getWrongValueException(PortableColumnEntity column, String text) {
        String shownValue = text.length() > 40 ? text.substring(0, 40) + "..." : text;
        return DbCopyException.badRequestCustom(__(DbCopyMessageEnum.WRONG_VALUE_X_X_X, shownValue, column.name(), column.family()));
    }

    private String getText(Object cell) {
        if (cell instanceof byte[] bytes) return new String(bytes, StandardCharsets.UTF_8);
        return String.valueOf(cell);
    }
}
