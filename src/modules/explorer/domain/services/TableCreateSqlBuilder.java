package modules.explorer.domain.services;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

import modules.shared.domain.services.SqlDialect;
import modules.shared.domain.services.SqlIdentifierQuoter;
import modules.shared.domain.services.SqlLiteralQuoter;

import static core.config.Global.__;

import modules.explorer.domain.enums.ExplorerMessageEnum;
import modules.explorer.domain.enums.ForeignKeyActionEnum;
import modules.explorer.domain.enums.TableIndexTypeEnum;
import modules.explorer.domain.entities.TableColumnEntity;
import modules.explorer.domain.entities.TableDefinitionEntity;
import modules.explorer.domain.entities.TableForeignKeyEntity;
import modules.explorer.domain.entities.TableIndexEntity;

/**
 * El "Create Table" de cada motor a partir de la tabla del editor. MySQL/MariaDB: el de TableAlterSqlBuilder (con
 * ENGINE, COLLATE...). El resto, lo comun y lo que cada uno pide:
 * <ul>
 * <li>PostgreSQL: auto incremento = GENERATED BY DEFAULT AS IDENTITY; indices normales en CREATE INDEX aparte;
 * comentarios con COMMENT ON TABLE/COLUMN.</li>
 * <li>SQLite: auto incremento solo en una PK de una columna INTEGER (INTEGER PRIMARY KEY AUTOINCREMENT); indices en
 * CREATE INDEX aparte; sin comentarios.</li>
 * <li>SQL Server: IDENTITY(1,1); RESTRICT = NO ACTION; sin comentarios. Cada sentencia va por
 * [bd].sys.sp_executesql: el REFERENCES de una clave foranea no admite el nombre de la BD y asi se resuelve en ella
 * aunque la sesion este en otra.</li>
 * </ul>
 * UNSIGNED, ZEROFILL, ON UPDATE, juego de caracteres, prefijos de indice, FULLTEXT/SPATIAL y las opciones de Avanzado
 * son de MySQL: en otro motor son un error, no se ignoran.
 */
public final class TableCreateSqlBuilder {

    private static final String CLAUSE_SEPARATOR = ",\n    ";
    private static final String SQLITE_INTEGER = "INTEGER";
    private static final String MSSQL_EXECUTE_SQL = "EXEC %s.sys.sp_executesql %s";

    private final boolean isSqlEngine;
    private final SqlDialect sqlDialect;
    private final SqlIdentifierQuoter sqlIdentifierQuoter;
    private final SqlLiteralQuoter sqlLiteralQuoter;
    private final TableNameValidator tableNameValidator;
    private final TableAlterSqlBuilder tableAlterSqlBuilder;

    private TableCreateSqlBuilder(String dbEngine) {
        this.isSqlEngine = SqlDialect.SQL_ENGINES.contains(dbEngine) || SqlDialect.FILES.equals(dbEngine);
        this.sqlDialect = SqlDialect.getInstance(dbEngine);
        this.sqlIdentifierQuoter = SqlIdentifierQuoter.getInstance(sqlDialect.getDbEngine());
        this.sqlLiteralQuoter = SqlLiteralQuoter.getInstance(sqlDialect.getDbEngine());
        this.tableNameValidator = TableNameValidator.getInstance(sqlDialect.getDbEngine());
        this.tableAlterSqlBuilder = TableAlterSqlBuilder.getInstance();
    }

    public static TableCreateSqlBuilder getInstance(String dbEngine) {
        return new TableCreateSqlBuilder(dbEngine);
    }

    /**
     * Los motores SQL (Redis y MongoDB no tienen tablas).
     */
    public boolean isSupported() {
        return isSqlEngine;
    }

    /**
     * Lo que impide crearla. Vacio = se puede.
     */
    public List<String> getErrors(TableDefinitionEntity edited) {
        if (sqlDialect.isMysql()) return tableAlterSqlBuilder.getErrors(edited);
        List<String> errors = new ArrayList<>();
        if (!tableNameValidator.isValid(edited.tableName())) errors.add(__(ExplorerMessageEnum.INVALID_TABLE_NAME_X, edited.tableName()));
        if (edited.columns().isEmpty()) errors.add(__(ExplorerMessageEnum.TABLE_WITHOUT_COLUMNS));
        Set<String> columnNames = new HashSet<>();
        for (TableColumnEntity column : edited.columns()) {
            if (!tableNameValidator.isValidColumn(column.name())) errors.add(__(ExplorerMessageEnum.INVALID_COLUMN_NAME_X, column.name()));
            if (!columnNames.add(column.name().toLowerCase(Locale.ROOT))) errors.add(__(ExplorerMessageEnum.DUPLICATED_COLUMN_X, column.name()));
            if (column.dataType().isBlank()) errors.add(__(ExplorerMessageEnum.COLUMN_WITHOUT_TYPE_X, column.name()));
            addColumnErrors(column, edited, errors);
        }
        for (String primaryKeyColumn : edited.primaryKeyColumns()) {
            if (!columnNames.contains(primaryKeyColumn.toLowerCase(Locale.ROOT))) errors.add(__(ExplorerMessageEnum.UNKNOWN_COLUMN_X_IN_X, primaryKeyColumn, "PRIMARY KEY"));
        }
        addIndexErrors(edited, columnNames, errors);
        addForeignKeyErrors(edited, columnNames, errors);
        addTableOptionErrors(edited, errors);
        return errors;
    }

    /**
     * Las sentencias, en orden: CREATE TABLE y, segun el motor, CREATE INDEX y COMMENT ON.
     */
    public List<String> getStatements(String databaseName, TableDefinitionEntity edited) {
        if (sqlDialect.isMysql()) return tableAlterSqlBuilder.getCreateStatements(databaseName, edited);
        String quotedTable = sqlDialect.isMssql() ? sqlIdentifierQuoter.getQuoted(null, edited.tableName()) : sqlIdentifierQuoter.getQuoted(databaseName, edited.tableName());
        List<String> statements = new ArrayList<>();
        statements.add(getCreateTableSql(databaseName, quotedTable, edited));
        for (TableIndexEntity index : edited.indexes()) {
            if (TableIndexTypeEnum.INDEX.equals(index.indexType())) statements.add(getCreateIndexSql(databaseName, edited.tableName(), quotedTable, index));
        }
        if (sqlDialect.isPgsql()) addPgsqlComments(quotedTable, edited, statements);
        if (!sqlDialect.isMssql()) return statements;

        List<String> mssqlStatements = new ArrayList<>();
        for (String statement : statements) {
            mssqlStatements.add(MSSQL_EXECUTE_SQL.formatted(sqlIdentifierQuoter.getQuoted(databaseName), sqlLiteralQuoter.getLiteral(statement)));
        }
        return mssqlStatements;
    }

    private String getCreateTableSql(String databaseName, String quotedTable, TableDefinitionEntity edited) {
        boolean isSqliteRowId = isSqliteRowIdKey(edited);
        List<String> definitions = new ArrayList<>();
        for (TableColumnEntity column : edited.columns()) definitions.add(getColumnDefinition(column, isSqliteRowId));
        if (!edited.primaryKeyColumns().isEmpty() && !isSqliteRowId) definitions.add("PRIMARY KEY (" + getQuotedList(edited.primaryKeyColumns()) + ")");
        for (TableIndexEntity index : edited.indexes()) {
            if (TableIndexTypeEnum.UNIQUE.equals(index.indexType())) {
                definitions.add("CONSTRAINT " + sqlIdentifierQuoter.getQuoted(index.name()) + " UNIQUE (" + getQuotedList(index.columns()) + ")");
            }
        }
        for (TableForeignKeyEntity foreignKey : edited.foreignKeys()) definitions.add(getForeignKeyDefinition(databaseName, foreignKey));
        return "CREATE TABLE " + quotedTable + " (\n    " + String.join(CLAUSE_SEPARATOR, definitions) + "\n)";
    }

    /**
     * "precio" decimal(10,2) NOT NULL DEFAULT 0, con el auto incremento de cada motor.
     */
    private String getColumnDefinition(TableColumnEntity column, boolean isSqliteRowId) {
        if (isSqliteRowId && column.isAutoIncrement()) {
            return sqlIdentifierQuoter.getQuoted(column.name()) + " " + SQLITE_INTEGER + " PRIMARY KEY AUTOINCREMENT";
        }
        StringBuilder definition = new StringBuilder(sqlIdentifierQuoter.getQuoted(column.name())).append(' ').append(column.dataType().trim());
        if (!column.length().isBlank()) definition.append('(').append(column.length().trim()).append(')');
        if (column.isAutoIncrement()) definition.append(sqlDialect.isPgsql() ? " GENERATED BY DEFAULT AS IDENTITY" : " IDENTITY(1,1)");
        definition.append(column.isNotNull() ? " NOT NULL" : " NULL");
        if (!column.defaultSql().isBlank()) definition.append(" DEFAULT ").append(column.defaultSql().trim());
        return definition.toString();
    }

    /**
     * PostgreSQL: el nombre del indice va sin esquema (queda en el de la tabla). SQLite: el esquema va en el indice y la
     * tabla sin el. SQL Server: dentro de sp_executesql de la BD, esquema.tabla.
     */
    private String getCreateIndexSql(String databaseName, String tableName, String quotedTable, TableIndexEntity index) {
        String columns = " (" + getQuotedList(index.columns()) + ")";
        if (sqlDialect.isSqlite()) {
            return "CREATE INDEX " + sqlIdentifierQuoter.getQuoted(databaseName, index.name()) + " ON " + sqlIdentifierQuoter.getQuoted(tableName) + columns;
        }
        return "CREATE INDEX " + sqlIdentifierQuoter.getQuoted(index.name()) + " ON " + quotedTable + columns;
    }

    private String getForeignKeyDefinition(String databaseName, TableForeignKeyEntity foreignKey) {
        String referencedTable = sqlDialect.isPgsql()
            ? sqlIdentifierQuoter.getQuoted(databaseName, foreignKey.referencedTable())
            : sqlDialect.isMssql() ? sqlIdentifierQuoter.getQuoted(null, foreignKey.referencedTable()) : sqlIdentifierQuoter.getQuoted(foreignKey.referencedTable());
        return "CONSTRAINT " + sqlIdentifierQuoter.getQuoted(foreignKey.name())
            + " FOREIGN KEY (" + getQuotedList(foreignKey.columns()) + ")"
            + " REFERENCES " + referencedTable + " (" + getQuotedList(foreignKey.referencedColumns()) + ")"
            + " ON DELETE " + getForeignKeyAction(foreignKey.onDelete()) + " ON UPDATE " + getForeignKeyAction(foreignKey.onUpdate());
    }

    private String getForeignKeyAction(String action) {
        if (sqlDialect.isMssql() && ForeignKeyActionEnum.RESTRICT.equals(action)) return ForeignKeyActionEnum.NO_ACTION;
        return action;
    }

    private void addPgsqlComments(String quotedTable, TableDefinitionEntity edited, List<String> statements) {
        if (!edited.comment().isEmpty()) statements.add("COMMENT ON TABLE " + quotedTable + " IS " + sqlLiteralQuoter.getLiteral(edited.comment()));
        for (TableColumnEntity column : edited.columns()) {
            if (column.comment().isEmpty()) continue;
            statements.add("COMMENT ON COLUMN " + quotedTable + "." + sqlIdentifierQuoter.getQuoted(column.name()) + " IS " + sqlLiteralQuoter.getLiteral(column.comment()));
        }
    }

    /**
     * SQLite solo auto incrementa la PK de una columna INTEGER (el rowid).
     */
    private boolean isSqliteRowIdKey(TableDefinitionEntity edited) {
        if (!sqlDialect.isSqlite() || edited.primaryKeyColumns().size() != 1) return false;
        for (TableColumnEntity column : edited.columns()) {
            if (!column.isAutoIncrement()) continue;
            return column.name().equalsIgnoreCase(edited.primaryKeyColumns().getFirst()) && SQLITE_INTEGER.equalsIgnoreCase(column.dataType().trim());
        }
        return false;
    }

    private void addColumnErrors(TableColumnEntity column, TableDefinitionEntity edited, List<String> errors) {
        String engine = sqlDialect.getDbEngine();
        if (column.isUnsigned()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "UNSIGNED (" + column.name() + ")", engine));
        if (column.isZerofill()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "ZEROFILL (" + column.name() + ")", engine));
        if (!column.onUpdateSql().isBlank()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "ON UPDATE (" + column.name() + ")", engine));
        if (!column.characterSet().isBlank() || !column.collation().isBlank()) {
            errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "CHARACTER SET / COLLATE (" + column.name() + ")", engine));
        }
        if (!column.comment().isEmpty() && !sqlDialect.isPgsql()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "COMMENT (" + column.name() + ")", engine));
        if (!column.isAutoIncrement()) return;
        if (!column.defaultSql().isBlank()) errors.add(__(ExplorerMessageEnum.AUTO_INCREMENT_WITH_DEFAULT_X, column.name()));
        if (sqlDialect.isSqlite() && !isSqliteRowIdKey(edited)) errors.add(__(ExplorerMessageEnum.SQLITE_AUTO_INCREMENT_X, column.name()));
    }

    private void addIndexErrors(TableDefinitionEntity edited, Set<String> columnNames, List<String> errors) {
        Set<String> indexNames = new HashSet<>();
        for (TableIndexEntity index : edited.indexes()) {
            if (!tableNameValidator.isValidColumn(index.name())) errors.add(__(ExplorerMessageEnum.INVALID_INDEX_NAME_X, index.name()));
            if (!indexNames.add(index.name().toLowerCase(Locale.ROOT))) errors.add(__(ExplorerMessageEnum.DUPLICATED_INDEX_X, index.name()));
            if (index.columns().isEmpty()) errors.add(__(ExplorerMessageEnum.INDEX_WITHOUT_COLUMNS_X, index.name()));
            if (!TableIndexTypeEnum.INDEX.equals(index.indexType()) && !TableIndexTypeEnum.UNIQUE.equals(index.indexType())) {
                errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, index.indexType() + " (" + index.name() + ")", sqlDialect.getDbEngine()));
            }
            for (String indexColumn : index.columns()) {
                if (!columnNames.contains(indexColumn.toLowerCase(Locale.ROOT))) errors.add(__(ExplorerMessageEnum.UNKNOWN_COLUMN_X_IN_X, indexColumn, index.name()));
            }
        }
    }

    private void addForeignKeyErrors(TableDefinitionEntity edited, Set<String> columnNames, List<String> errors) {
        for (TableForeignKeyEntity foreignKey : edited.foreignKeys()) {
            if (!tableNameValidator.isValidColumn(foreignKey.name())) errors.add(__(ExplorerMessageEnum.INVALID_INDEX_NAME_X, foreignKey.name()));
            if (foreignKey.columns().isEmpty() || foreignKey.columns().size() != foreignKey.referencedColumns().size() || foreignKey.referencedTable().isBlank()) {
                errors.add(__(ExplorerMessageEnum.WRONG_FOREIGN_KEY_X, foreignKey.name()));
            }
            for (String foreignKeyColumn : foreignKey.columns()) {
                if (!columnNames.contains(foreignKeyColumn.toLowerCase(Locale.ROOT))) errors.add(__(ExplorerMessageEnum.UNKNOWN_COLUMN_X_IN_X, foreignKeyColumn, foreignKey.name()));
            }
        }
    }

    private void addTableOptionErrors(TableDefinitionEntity edited, List<String> errors) {
        String engine = sqlDialect.getDbEngine();
        if (!edited.engine().isBlank()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "ENGINE", engine));
        if (!edited.collation().isBlank()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "COLLATE", engine));
        if (!edited.autoIncrement().isBlank()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "AUTO_INCREMENT", engine));
        if (!edited.rowFormat().isBlank()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "ROW_FORMAT", engine));
        if (!edited.comment().isEmpty() && !sqlDialect.isPgsql()) errors.add(__(ExplorerMessageEnum.X_NOT_AVAILABLE_IN_X, "COMMENT", engine));
    }

    private String getQuotedList(List<String> identifiers) {
        List<String> quotedIdentifiers = new ArrayList<>();
        for (String identifier : identifiers) quotedIdentifiers.add(sqlIdentifierQuoter.getQuoted(identifier));
        return String.join(", ", quotedIdentifiers);
    }
}
